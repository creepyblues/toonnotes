/**
 * Post-build script that reads the Vite-built HTML file and generates
 * a TypeScript module exporting it as a string constant.
 * This allows React Native to load the HTML via WebView's `source={{ html }}`.
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(__dirname, '..', 'dist');
// The singlefile plugin preserves the directory structure, so the HTML
// is at dist/src/webview/index.html
const htmlPath = resolve(distDir, 'src', 'webview', 'index.html');

if (!existsSync(htmlPath)) {
  console.error('Build output not found at', htmlPath);
  process.exit(1);
}

const html = readFileSync(htmlPath, 'utf-8');

// Escape backticks and ${} in the HTML for template literal safety
const escaped = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const tsContent = `// Auto-generated by scripts/generate-html-export.mjs — do not edit
export const EDITOR_HTML = \`${escaped}\`;
`;

writeFileSync(resolve(distDir, 'editor-html.js'), tsContent);
writeFileSync(
  resolve(distDir, 'editor-html.d.ts'),
  'export declare const EDITOR_HTML: string;\n'
);

console.log('Generated dist/editor-html.js and dist/editor-html.d.ts');
